#!/usr/bin/env python3
"""Generate src/vectors_gen.rs from the reference vector files.

Inputs (committed beside this script, checksums recorded in spike-notes.md):
  vectors/bip340.csv          — BIP-340 test vectors (bitcoin/bips master)
  vectors/nip44.vectors.json  — NIP-44 v2 vectors, sha256
                                269ed0f69e4c192512cc779e78c555090cebc7c785b609e338a62afc3ce25040
                                (the checksum the NIP itself publishes)

The generator is committed so regeneration is reproducible; the generated file
is byte-literal arrays so the same constants serve a no_std device build.
"""
import base64
import csv
import io
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
BIP340 = REPO / "vectors" / "bip340.csv"
NIP44 = REPO / "vectors" / "nip44.vectors.json"
OUT = REPO / "src" / "vectors_gen.rs"


def hx(hexstr: str, n: int) -> str:
    b = bytes.fromhex(hexstr)
    assert len(b) == n, f"expected {n} bytes, got {len(b)}"
    return "[" + ", ".join(f"0x{x:02x}" for x in b) + "]"


def hopt(hexstr: str, n: int) -> str:
    return "Some(" + hx(hexstr, n) + ")" if hexstr else "None"


def bytes_lit(data: bytes) -> str:
    """A u8 array literal standing in for a fixed byte string."""
    return "[" + ", ".join(f"0x{x:02x}" for x in data) + "]"


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def xonly_pub2(sec2_hex: str) -> str:
    """The x-only public key of the vector's second secret key.

    The reference vectors carry both parties' *secrets*; the ECDH leg is
    exercised against sec2's x-only public key, so the generator derives it
    here (pure-python affine arithmetic — 11 rows, speed irrelevant).
    """
    p = 2**256 - 2**32 - 977
    gx = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
    gy = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8

    def ec_add(P, Q):
        if P is None:
            return Q
        if Q is None:
            return P
        x1, y1 = P
        x2, y2 = Q
        if x1 == x2 and (y1 + y2) % p == 0:
            return None
        if P == Q:
            lam = (3 * x1 * x1) * pow(2 * y1, p - 2, p) % p
        else:
            lam = (y2 - y1) * pow(x2 - x1, p - 2, p) % p
        x3 = (lam * lam - x1 - x2) % p
        return (x3, (lam * (x1 - x3) - y1) % p)

    k = int(sec2_hex, 16)
    Q = None
    Gpt = (gx, gy)
    while k:
        if k & 1:
            Q = ec_add(Q, Gpt)
        Gpt = ec_add(Gpt, Gpt)
        k >>= 1
    assert Q is not None and Q[0] != 0
    return f"{Q[0]:064x}"


def main() -> int:
    rows = list(csv.DictReader(io.StringIO(BIP340.read_text())))
    assert rows, "no BIP-340 rows"
    d = json.loads(NIP44.read_text())["v2"]
    valid, invalid = d["valid"], d["invalid"]

    out = io.StringIO()
    out.write("""//! Generated by tools/gen_vectors.py — do not edit.
//! Sources: vectors/bip340.csv (BIP-340 reference test vectors) and
//! vectors/nip44.vectors.json (sha256 269ed0f69e4c192512cc779e78c555090cebc7c785b609e338a62afc3ce25040,
//! the checksum NIP-44 itself publishes).
#![allow(non_upper_case_globals)]

""")

    # --- BIP-340 -----------------------------------------------------------
    out.write("/// BIP-340 reference test vectors.\n#[derive(Clone, Copy)]\n")
    out.write("pub struct Bip340Vector {\n    pub index: u32,\n")
    out.write("    pub sk: Option<[u8; 32]>,\n    pub pk: Option<[u8; 32]>,\n")
    out.write("    /// Aux bytes exist only where a sign assertion applies.\n")
    out.write("    pub aux: Option<[u8; 32]>,\n")
    out.write("    /// Message length is variable (the 2022-12 rows exercise 0/1/17/100 bytes).\n")
    out.write("    pub msg: &'static [u8],\n")
    out.write("    pub sig: Option<[u8; 64]>,\n")
    out.write("    /// `Some(expected)` wherever a verify assertion applies.\n")
    out.write("    pub verify_ok: Option<bool>,\n    pub comment: &'static str,\n}\n")
    out.write("\npub const BIP340_VECTORS: &[Bip340Vector] = &[\n")
    for r in rows:
        sig = r["signature"].strip()
        verify = None
        if sig:
            verify = r["verification result"].strip().upper() == "TRUE"
        out.write("    Bip340Vector {\n")
        out.write(f"        index: {r['index'].strip()},\n")
        out.write(f"        sk: {hopt(r['secret key'].strip(), 32)},\n")
        out.write(f"        pk: {hopt(r['public key'].strip(), 32)},\n")
        out.write(f"        aux: {hopt(r['aux_rand'].strip(), 32)},\n")
        out.write(f"        msg: &{bytes_lit(bytes.fromhex(r['message'].strip()))},\n")
        out.write(f"        sig: {hopt(sig, 64)},\n")
        out.write(f"        verify_ok: {'Some(true)' if verify is True else 'Some(false)' if verify is False else 'None'},\n")
        out.write(f"        comment: \"{esc(r['comment'].strip())}\",\n")
        out.write("    },\n")
    out.write("];\n\n")

    # --- NIP-44 conversation key ------------------------------------------
    out.write("/// NIP-44 v2 `get_conversation_key` valid vectors.\n")
    out.write("pub struct ConvKeyVector {\n    pub sk: [u8; 32],\n    pub peer_x: [u8; 32],\n    pub ck: [u8; 32],\n}\n")
    out.write("\npub const CONV_KEY_VECTORS: &[ConvKeyVector] = &[\n")
    for v in valid["get_conversation_key"]:
        out.write("    ConvKeyVector {\n")
        out.write(f"        sk: {hx(v['sec1'], 32)},\n")
        out.write(f"        peer_x: {hx(v['pub2'], 32)},\n")
        out.write(f"        ck: {hx(v['conversation_key'], 32)},\n")
        out.write("    },\n")
    out.write("];\n\n")

    out.write("/// NIP-44 v2 `get_conversation_key` vectors that must be refused.\n")
    out.write("pub struct ConvKeyInvalidVector {\n    pub sk: [u8; 32],\n    pub peer_x: [u8; 32],\n    pub note: &'static str,\n}\n")
    out.write("\npub const CONV_KEY_INVALID: &[ConvKeyInvalidVector] = &[\n")
    for v in invalid["get_conversation_key"]:
        out.write("    ConvKeyInvalidVector {\n")
        out.write(f"        sk: {hx(v['sec1'], 32)},\n")
        out.write(f"        peer_x: {hx(v['pub2'], 32)},\n")
        out.write(f"        note: \"{esc(v['note'])}\",\n")
        out.write("    },\n")
    out.write("];\n\n")

    # --- NIP-44 message keys ----------------------------------------------
    out.write("/// NIP-44 v2 `get_message_keys` vectors (one conversation key).\n")
    out.write("pub struct MessageKeysVector {\n    pub nonce: [u8; 32],\n    pub chacha_key: [u8; 32],\n")
    out.write("    pub chacha_nonce: [u8; 12],\n    pub hmac_key: [u8; 32],\n}\n")
    mk = valid["get_message_keys"]
    cks = mk["conversation_key"]
    assert isinstance(cks, str) and len(cks) == 64, "unexpected get_message_keys shape"
    out.write(f"pub const MESSAGE_KEYS_CK: [u8; 32] = {hx(cks, 32)};\n")
    out.write("\npub const MESSAGE_KEYS_VECTORS: &[MessageKeysVector] = &[\n")
    for k in mk["keys"]:
        out.write("    MessageKeysVector {\n")
        out.write(f"        nonce: {hx(k['nonce'], 32)},\n")
        out.write(f"        chacha_key: {hx(k['chacha_key'], 32)},\n")
        out.write(f"        chacha_nonce: {hx(k['chacha_nonce'], 12)},\n")
        out.write(f"        hmac_key: {hx(k['hmac_key'], 32)},\n")
        out.write("    },\n")
    out.write("];\n\n")

    # --- calc_padded_len ---------------------------------------------------
    out.write("/// `[unpadded_len, padded_len]` pairs from the reference vectors.\n")
    out.write("pub const CALC_PADDED_LEN_VECTORS: &[(u64, u64)] = &[\n")
    for a, b in valid["calc_padded_len"]:
        out.write(f"    ({a}, {b}),\n")
    out.write("];\n\n")

    # --- encrypt/decrypt ---------------------------------------------------
    def payload(entry: dict) -> bytes:
        # Some refusal vectors deliberately corrupt the payload (a '#' in the
        # base64, a bad version byte), so decode leniently: a2b_base64 drops
        # non-alphabet characters, which is what a strict decoder refuses
        # upstream — the device sees raw bytes and refuses them at its own
        # parse layer. Padding is normalized first; the vectors carry none.
        import binascii
        import re
        # Drop non-alphabet chars first (a corrupted vector carries '#'),
        # then normalize padding, then decode leniently.
        p = re.sub(r"[^A-Za-z0-9+/=]", "", entry["payload"].strip())
        return binascii.a2b_base64((p + "=" * (-len(p) % 4)).encode("utf-8"))

    out.write("/// NIP-44 v2 encrypt/decrypt round-trip vectors.\n")
    out.write("pub struct EncryptDecryptVector {\n    pub sk: [u8; 32],\n    pub peer_x: [u8; 32],\n")
    out.write("    pub ck: [u8; 32],\n    pub nonce: [u8; 32],\n    pub plaintext: &'static [u8],\n")
    out.write("    pub payload: &'static [u8],\n}\n")
    out.write("\npub const ENCRYPT_DECRYPT_VECTORS: &[EncryptDecryptVector] = &[\n")
    for v in valid["encrypt_decrypt"]:
        pt = v["plaintext"].encode("utf-8")
        out.write("    EncryptDecryptVector {\n")
        out.write(f"        sk: {hx(v['sec1'], 32)},\n")
        out.write(f"        peer_x: {hx(xonly_pub2(v['sec2']), 32)},\n")
        # conversation_key listed for cross-checking the ECDH leg; the round-trip
        # test re-derives it from (sk, peer_x) and asserts equality first.
        out.write(f"        ck: {hx(v['conversation_key'], 32)},\n")
        out.write(f"        nonce: {hx(v['nonce'], 32)},\n")
        out.write(f"        plaintext: &{bytes_lit(pt)},\n")
        out.write(f"        payload: &{bytes_lit(payload(v))},\n")
        out.write("    },\n")
    out.write("];\n\n")

    # --- invalid decrypt ---------------------------------------------------
    out.write("/// NIP-44 v2 payloads that must be refused on decrypt, with the reason.\n")
    out.write("pub struct DecryptInvalidVector {\n    pub ck: [u8; 32],\n    pub nonce: [u8; 32],\n")
    out.write("    pub payload: &'static [u8],\n    pub note: &'static str,\n}\n")
    out.write("\npub const DECRYPT_INVALID: &[DecryptInvalidVector] = &[\n")
    for v in invalid["decrypt"]:
        out.write("    DecryptInvalidVector {\n")
        out.write(f"        ck: {hx(v['conversation_key'], 32)},\n")
        out.write(f"        nonce: {hx(v['nonce'], 32)},\n")
        out.write(f"        payload: &{bytes_lit(payload(v))},\n")
        out.write(f"        note: \"{esc(v['note'])}\",\n")
        out.write("    },\n")
    out.write("];\n\n")

    # --- long messages (sha256-anchored) -----------------------------------
    out.write("/// Long-message encrypt vectors: the plaintext is `pattern` (UTF-8)\n")
    out.write("/// repeated `repeat` times, sha256 `plaintext_sha256`; encrypting under\n")
    out.write("/// (`ck`, `nonce`) must produce a payload sha256 `payload_sha256`.\n")
    out.write("pub struct LongMsgVector {\n    pub ck: [u8; 32],\n    pub nonce: [u8; 32],\n")
    out.write("    pub pattern: &'static [u8],\n    pub repeat: u32,\n")
    out.write("    pub plaintext_sha256: [u8; 32],\n    pub payload_sha256: [u8; 32],\n}\n")
    out.write("\npub const LONG_MSG_VECTORS: &[LongMsgVector] = &[\n")
    for v in valid["encrypt_decrypt_long_msg"]:
        pat = v["pattern"].encode("utf-8")
        out.write("    LongMsgVector {\n")
        out.write(f"        ck: {hx(v['conversation_key'], 32)},\n")
        out.write(f"        nonce: {hx(v['nonce'], 32)},\n")
        out.write(f"        pattern: &{bytes_lit(pat)},\n")
        out.write(f"        repeat: {v['repeat']},\n")
        out.write(f"        plaintext_sha256: {hx(v['plaintext_sha256'], 32)},\n")
        out.write(f"        payload_sha256: {hx(v['payload_sha256'], 32)},\n")
        out.write("    },\n")
    out.write("];\n\n")

    out.write("/// Plaintext lengths the encrypt path must refuse (`encrypt_msg_lengths`).\n")
    out.write("pub const ENCRYPT_FORBIDDEN_LEN: &[u64] = &[\n")
    for n in invalid["encrypt_msg_lengths"]:
        out.write(f"    {n},\n")
    out.write("];\n")

    OUT.write_text(out.getvalue())
    print(f"wrote {OUT} ({len(out.getvalue())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
