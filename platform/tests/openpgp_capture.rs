//! Producer whitelist regression: physical object records and stored identity DOs.
use fapico2_platform::cfs::is_migratable_fid;

#[test]
fn merged_openpgp_identity_records_are_capturable() {
    for fid in [
        0x1081, 0x1082, 0x1083, 0x1099, 0x109a, 0x109b, 0x109c,
        0x10c1, 0x10c2, 0x10c3, 0x10c4, 0x10c5,
        0x10d1, 0x10d2, 0x10d3, 0x10d4, 0x10d5, 0x10d6,
        0xe8d1, 0xe9d1, 0xead1, 0xebd1, 0xecd1, 0xedd1,
        0xe8d2, 0xedd3,
        0x004f, 0x005b, 0x005e, 0x0093,
        0x00c7, 0x00c8, 0x00c9, 0x00ca, 0x00cb, 0x00cc,
        0x00ce, 0x00cf, 0x00d0, 0x00d6, 0x00d7, 0x00d8,
        0x5f2d, 0x5f35, 0x5f50,
    ] {
        assert!(is_migratable_fid(fid), "missing merged C record {fid:04x}");
    }
    // Physical prefixes are not a license to capture unrelated containers.
    for fid in [0xe800, 0xe8d0, 0xe8d4, 0xead4, 0xedff, 0xeeee] {
        assert!(!is_migratable_fid(fid), "unrelated record {fid:04x}");
    }
}
