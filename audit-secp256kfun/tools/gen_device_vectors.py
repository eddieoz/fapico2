#!/usr/bin/env python3
"""Generate differential test vectors for secp256kfun 0.12.1's DEVICE backends.

The RP2350 (thumbv8m) compiles field_10x26.rs and scalar_8x32.rs; hosts
compile field_5x52.rs and scalar_4x64.rs. The probe crate includes the
device sources verbatim on the host, and this generator produces the
expected values from plain modular arithmetic — an implementation the
device code never consults.

Output: audit-secp256kfun/src/device_vectors.rs (GENERATED — do not edit).
Run:    python3 audit-secp256kfun/tools/gen_device_vectors.py
"""
import random

p = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
n = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141

rng = random.Random(0xFACADE)

def h32(x):
    return x.to_bytes(32, "big")

def be(b):
    return ", ".join(f"0x{x:02x}" for x in b)

def bytes_lit(b):
    return "[" + be(b) + "]"

field_cases = []      # (a, b) both in [0, p)
field_invalid = []    # byte encodings rejected by from_bytes (>= p)
scalar_cases = []     # (a, b) both in [0, n)
scalar_invalid = []   # byte encodings rejected by from_bytes (>= n)
scalar_reduced = []   # (bytes, expected) for from_bytes_reduced

# ---- edge values -----------------------------------------------------------
field_edges = [0, 1, 2, 3, p - 2, p - 1, 0x1000003D0, 0x1000003D1 - 1, 1 << 128, (1 << 128) + 1]
scalar_edges = [0, 1, 2, 3, n - 2, n - 1, n // 2, n // 2 + 1, 1 << 128, (1 << 255), (1 << 255) - 1]

for _ in range(60):
    field_edges.append(rng.randrange(p))
    scalar_edges.append(rng.randrange(n))

# field op cases: edges × edges would be 20×20 = 400; take a stride plus pairs
fe = field_edges
pairs = [(fe[i], fe[(i * 7 + 3) % len(fe)]) for i in range(len(fe))]
for a in fe:
    pairs.append((a, a))          # doubling/squaring cases
    pairs.append((a, 0))
    pairs.append((0, a))
for _ in range(40):
    pairs.append((rng.randrange(p), rng.randrange(p)))

seen = set()
for a, b in pairs:
    if (a, b) in seen:
        continue
    seen.add((a, b))
    field_cases.append({
        "a": h32(a), "b": h32(b),
        "mul": h32(a * b % p),
        "sq": h32(a * a % p),
        "add": h32((a + b) % p),
        "neg": h32((-a) % p),
        "a_odd": a & 1 == 1,
    })

# from_bytes refusals: encodings in [p, 2^256) must be refused
for v in [p, p + 1, 2**256 - 1, p + 2**32]:
    field_invalid.append((h32(v), False))  # all are >= p

# scalar cases
spairs = []
se = scalar_edges
for i in range(len(se)):
    spairs.append((se[i], se[(i * 5 + 1) % len(se)]))
    spairs.append((se[i], se[i]))
for _ in range(40):
    spairs.append((rng.randrange(n), rng.randrange(n)))
for a, b in spairs:
    scalar_cases.append({
        "a": h32(a), "b": h32(b),
        "add": h32((a + b) % n),
        "sub": h32((a - b) % n),
        "mul": h32(a * b % n),
        "a_high": a > n // 2,
        "neg": h32((-a) % n),
    })

# from_bytes refusals + from_bytes_reduced expectations for [n, 2^256) inputs
for v in [n, n + 1, 2**256 - 1, n + 2**64]:
    scalar_invalid.append((h32(v), False))  # all are >= n
    scalar_reduced.append((h32(v), h32(v % n)))

# ---- emit -------------------------------------------------------------------
out = []
out.append("// GENERATED by audit-secp256kfun/tools/gen_device_vectors.py — do not edit.")
out.append("// Differential oracle for the thumbv8m backends (field_10x26, scalar_8x32):")
out.append("// every expected value is plain modular arithmetic computed in python.")
out.append("")
out.append("pub struct FieldCase {")
out.append("    pub a: [u8; 32],")
out.append("    pub b: [u8; 32],")
out.append("    pub mul: [u8; 32],")
out.append("    pub sq: [u8; 32],")
out.append("    pub add: [u8; 32],")
out.append("    pub neg: [u8; 32],")
out.append("    pub a_odd: bool,")
out.append("}")
out.append("")
out.append(f"pub const FIELD_CASES: &[FieldCase] = &[")
for c in field_cases:
    out.append("    FieldCase {")
    for k in ("a", "b", "mul", "sq", "add", "neg"):
        out.append(f"        {k}: {bytes_lit(c[k])},")
    out.append(f"        a_odd: {str(c['a_odd']).lower()},")
    out.append("    },")
out.append("];")
out.append("")
out.append("/// (bytes, from_bytes_should_accept) — accept iff value < p.")
out.append("pub const FIELD_FROM_BYTES: &[([u8; 32], bool)] = &[")
for b, ok in field_invalid:
    out.append(f"    ({bytes_lit(b)}, {str(ok).lower()}),")
out.append("];")
out.append("")
out.append("pub struct ScalarCase {")
out.append("    pub a: [u8; 32],")
out.append("    pub b: [u8; 32],")
out.append("    pub add: [u8; 32],")
out.append("    pub sub: [u8; 32],")
out.append("    pub mul: [u8; 32],")
out.append("    pub a_high: bool,")
out.append("    pub neg: [u8; 32],")
out.append("}")
out.append("")
out.append("pub const SCALAR_CASES: &[ScalarCase] = &[")
for c in scalar_cases:
    out.append("    ScalarCase {")
    for k in ("a", "b", "add", "sub", "mul", "neg"):
        out.append(f"        {k}: {bytes_lit(c[k])},")
    out.append(f"        a_high: {str(c['a_high']).lower()},")
    out.append("    },")
out.append("];")
out.append("")
out.append("/// (bytes, from_bytes_should_accept) — accept iff value < n.")
out.append("pub const SCALAR_FROM_BYTES: &[([u8; 32], bool)] = &[")
for b, ok in scalar_invalid:
    out.append(f"    ({bytes_lit(b)}, {str(ok).lower()}),")
out.append("];")
out.append("")
out.append("/// (input_bytes >= n, expected from_bytes_reduced) — inputs the")
out.append("/// strict from_bytes must refuse but the mod-order path must fold.")
out.append("pub const SCALAR_REDUCED: &[([u8; 32], [u8; 32])] = &[")
for b, r in scalar_reduced:
    out.append(f"    ({bytes_lit(b)}, {bytes_lit(r)}),")
out.append("];")

path = __file__.rsplit("/", 2)[0] + "/src/device_vectors.rs"
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {path}: {len(field_cases)} field cases, {len(scalar_cases)} scalar cases, "
      f"{len(field_invalid)}+{len(scalar_invalid)} refusal rows, {len(scalar_reduced)} reduced rows")
