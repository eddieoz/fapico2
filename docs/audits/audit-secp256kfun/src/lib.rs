// --- the DEVICE scalar backend (8 x 32-bit u32 limbs) ----------------------
pub mod device_scalar {
    /// `adc32`/`sbb32` verbatim from the registry `util.rs`, cfg gate stripped
    /// (upstream compiles them only on 32-bit targets; the included verbatim
    /// scalar_8x32.rs calls them and we run on a 64-bit host).
    pub mod util {
        #[inline(always)]
        pub const fn adc32(a: u32, b: u32, carry: u32) -> (u32, u32) {
            let ret = (a as u64) + (b as u64) + (carry as u64);
            (ret as u32, (ret >> 32) as u32)
        }
        #[inline(always)]
        pub const fn sbb32(a: u32, b: u32, borrow: u32) -> (u32, u32) {
            let ret = (a as u64).wrapping_sub((b as u64) + ((borrow >> 31) as u64));
            (ret as u32, (ret >> 32) as u32)
        }
    }

    pub mod scalar {
        pub type FieldBytes = generic_array::GenericArray<u8, generic_array::typenum::U32>;
        #[path = "/home/eddieoz/.cargo/registry/src/index.crates.io-1949cf8c6b5b557f/secp256kfun-0.12.1/src/vendor/k256/scalar/scalar_8x32.rs"]
        pub mod scalar_8x32;
        pub use scalar_8x32::Scalar8x32;
    }
    pub use scalar::Scalar8x32;
}

