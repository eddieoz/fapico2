// ---------------------------------------------------------------------------
// Differential tests: device backends vs the python oracle.
// ---------------------------------------------------------------------------
#[cfg(test)]
mod device_differential {
    use super::device_field::FieldElement10x26;
    use super::device_scalar::Scalar8x32;
    use super::device_vectors::*;
    use subtle::{CtOption, ConstantTimeEq};

    fn ct_into<T: Copy>(ct: CtOption<T>) -> Option<T> {
        ct.into()
    }

    #[test]
    fn device_field_mul_sq_add_neg_match_the_oracle() {
        for (i, case) in FIELD_CASES.iter().enumerate() {
            let a = ct_into(FieldElement10x26::from_bytes((&case.a).into()))
                .unwrap_or_else(|| panic!("case {i}: a must be < p"));
            let b = ct_into(FieldElement10x26::from_bytes((&case.b).into()))
                .unwrap_or_else(|| panic!("case {i}: b must be < p"));

            assert_eq!(a.mul(&b).normalize().to_bytes().as_slice(), &case.mul[..], "case {i} mul");
            assert_eq!(a.square().normalize().to_bytes().as_slice(), &case.sq[..], "case {i} sq");
            assert_eq!(a.add(&b).normalize().to_bytes().as_slice(), &case.add[..], "case {i} add");
            assert_eq!(a.negate(1).normalize().to_bytes().as_slice(), &case.neg[..], "case {i} neg");
            assert_eq!(a.is_odd().unwrap_u8() == 1, case.a_odd, "case {i} is_odd");
            // round trip: a normalized element serializes to itself
            assert_eq!(a.to_bytes().as_slice(), &case.a[..], "case {i} round-trip");
            assert_eq!(b.to_bytes().as_slice(), &case.b[..], "case {i} round-trip b");
        }
    }

    #[test]
    fn device_field_from_bytes_range_gate() {
        for (bytes, accept) in FIELD_FROM_BYTES {
            let got = ct_into(FieldElement10x26::from_bytes(bytes.into()));
            assert_eq!(got.is_some(), *accept, "bytes {:02x?}", &bytes[..8]);
        }
    }

    #[test]
    fn device_field_normalize_is_idempotent_and_canonical() {
        for case in FIELD_CASES.iter().take(32) {
            let a = ct_into(FieldElement10x26::from_bytes((&case.a).into())).unwrap();
            let n1 = a.normalize();
            let n2 = n1.normalize();
            assert_eq!(n1.to_bytes(), n2.to_bytes());
            assert!(ct_eq(&n1, &n2));
        }
    }

    fn ct_eq(a: &FieldElement10x26, b: &FieldElement10x26) -> bool {
        subtle::ConstantTimeEq::ct_eq(a, b).unwrap_u8() == 1
    }

    #[test]
    fn device_scalar_add_sub_mul_match_the_oracle() {
        for (i, case) in SCALAR_CASES.iter().enumerate() {
            let a = ct_into(Scalar8x32::from_bytes((&case.a).into()))
                .unwrap_or_else(|| panic!("case {i}: a must be < n"));
            let b = ct_into(Scalar8x32::from_bytes((&case.b).into()))
                .unwrap_or_else(|| panic!("case {i}: b must be < n"));

            assert_eq!(a.add(&b).to_bytes().as_slice(), &case.add[..], "case {i} add");
            assert_eq!(a.sub(&b).to_bytes().as_slice(), &case.sub[..], "case {i} sub");
            assert_eq!(a.mul(&b).to_bytes().as_slice(), &case.mul[..], "case {i} mul");
            assert_eq!(a.is_high().unwrap_u8() == 1, case.a_high, "case {i} is_high");
            assert_eq!(a.negate().to_bytes().as_slice(), &case.neg[..], "case {i} neg");
            assert_eq!(a.to_bytes().as_slice(), &case.a[..], "case {i} round-trip");
        }
    }

    #[test]
    fn device_scalar_from_bytes_range_gate_and_mod_order_fold() {
        for (bytes, accept) in SCALAR_FROM_BYTES {
            assert_eq!(
                ct_into(Scalar8x32::from_bytes(bytes.into())).is_some(),
                *accept,
                "bytes {:02x?}",
                &bytes[..8]
            );
        }
        for (input, expected) in SCALAR_REDUCED {
            let reduced = Scalar8x32::from_bytes_reduced(input);
            assert_eq!(reduced.to_bytes().as_slice(), &expected[..], "input {:02x?}", &input[..8]);
        }
    }

    // keep the crate's own regression tests' imports used
    #[allow(dead_code)]
    fn _touch(_c: FieldElement10x26) {}
}
