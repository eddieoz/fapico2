//! Audit probes for `secp256kfun 0.12.1` as used by the fapico2 Nostr applet.
//!
//! Two properties make this harness trustworthy:
//!
//! 1. **The applet code under test is the live source.** `crypto` and `nip44`
//!    are `#[path]`-included from `apps/nostr/src/` — no copies, so no drift.
//! 2. **The device arithmetic is exercised, not the host arithmetic.** The
//!    RP2350 (thumbv8m, 32-bit) compiles `field_10x26.rs` + `scalar_8x32.rs`
//!    while every host test in the repo compiles `field_5x52.rs` +
//!    `scalar_4x64.rs`. The shims below include the *device* sources verbatim
//!    on the host and differential-test them against
//!    `device_vectors.rs` (generated by `tools/gen_device_vectors.py` from
//!    plain modular arithmetic — an independent oracle).

